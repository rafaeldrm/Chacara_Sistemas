//====================================================================================
//                   VARIÁVEIS INTERNAS
//====================================================================================

static uint16_t mapaAtual = 0;

//====================================================================================
//                   SETUP
//====================================================================================

void Leitura_Eco_Hidro_Boias_Inicializa()
{



}

//====================================================================================
//                   LOOP
//====================================================================================



void Leitura_Boias_Atualiza(uint16_t novoMapa)
{
    mapaAtual = novoMapa;
}

//====================================================================================
//                   LEITURA BOIAS ESTA ATIVA
//====================================================================================

bool Leitura_Boias_Esta_Ativa(REGISTRO_BOIAS::BOIA_BIT boia)
{
    return (mapaAtual & (uint16_t(1) << boia)) != 0;
}

uint16_t Leitura_Boias_Mapa_Completo()
{
    return mapaAtual;
}